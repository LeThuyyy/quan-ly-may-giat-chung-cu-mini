'use client';
import { useEffect, useState } from 'react';

export default function MachineQrButton(props: { buildingId: string; machineId: string; onSessionExpired?: () => void }) {
  return <QrButton key={`${props.buildingId}:${props.machineId}`} {...props} />;
}
function QrButton({ buildingId, machineId, onSessionExpired }: { buildingId: string; machineId: string; onSessionExpired?: () => void }) {
  const [requested, setRequested] = useState(false);
  const [url, setUrl] = useState<string | null>(null);
  const [error, setError] = useState('');
  useEffect(() => {
    if (!requested) return;
    const abort = new AbortController(); let active = true; let objectUrl: string | null = null;
    void (async () => {
      try {
        const response = await fetch(`/api/buildings/${buildingId}/machines/${machineId}/qr`, { cache: 'no-store', signal: abort.signal });
        if (!active) return;
        if (response.status === 401) { onSessionExpired?.(); return; }
        if (!response.ok) throw new Error('Không tạo được QR. Hãy tải lại trang và kiểm tra quyền truy cập.');
        const blob = await response.blob();
        if (!active) return;
        objectUrl = URL.createObjectURL(blob); setUrl(objectUrl);
      } catch { if (active && !abort.signal.aborted) setError('Không tạo được QR. Hãy tải lại trang và kiểm tra quyền truy cập.'); }
    })();
    return () => { active = false; abort.abort(); if (objectUrl) URL.revokeObjectURL(objectUrl); };
  }, [requested, buildingId, machineId, onSessionExpired]);
  return <section className="qr-card" aria-label="Mã QR máy">
    <button type="button" className="btn btn-outline btn-sm" disabled={requested} onClick={() => setRequested(true)}>Hiện mã QR của máy</button>
    {error && <p className="alert alert-error" role="alert">{error}</p>}
    {url && <><p className="muted-note">QR chỉ mở trang máy, không cấp quyền hoặc xác nhận máy trống. Địa chỉ QR do máy chủ cấu hình.</p>
      {/* Blob is generated by the authenticated local QR route, not arbitrary markup. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={url} alt="QR mở trang chi tiết máy" width={220} height={220} />
      <a className="btn btn-primary btn-sm" href={url} download="machine-qr.svg">Tải mã QR SVG</a></>}
  </section>;
}
